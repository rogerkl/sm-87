/* the panel: a yellow-green backlit LCD */
#define LCD_GLASS RGB(150, 186, 44)
#define LCD_OFF RGB(140, 174, 40)
#define LCD_ON RGB(30, 46, 12)
#define LCD_EDGE RGB(60, 70, 30)

static char lcd_txt[LCD_ROWS][LCD_COLS + 1];
static int8_t lcd_cur_row = -1, lcd_cur_col;   /* the cursor (an underline), -1: none */
static uint8_t lcd_changed = 1;

static void lcd_clear(void)
{
    uint32_t r, c;
    for (r = 0; r < LCD_ROWS; r++) {
        for (c = 0; c < LCD_COLS; c++)
            lcd_txt[r][c] = ' ';
        lcd_txt[r][LCD_COLS] = 0;
    }
    lcd_cur_row = -1;
    lcd_changed = 1;
}

/* text at a place, cut at the row's end */
static void lcd_at(uint32_t row, uint32_t col, const char *s)
{
    while (*s && col < LCD_COLS && row < LCD_ROWS) {
        if (lcd_txt[row][col] != *s) {
            lcd_txt[row][col] = *s;
            lcd_changed = 1;
        }
        s++;
        col++;
    }
}

/* a whole row: the text, then spaces */
static void lcd_row(uint32_t row, const char *s)
{
    char t[LCD_COLS + 1];
    uint32_t i = 0;
    while (s && s[i] && i < LCD_COLS) {
        t[i] = s[i];
        i++;
    }
    while (i < LCD_COLS)
        t[i++] = ' ';
    t[LCD_COLS] = 0;
    lcd_at(row, 0, t);
}

static void lcd_cursor(int32_t row, int32_t col)
{
    if (lcd_cur_row != row || lcd_cur_col != col) {
        lcd_cur_row = (int8_t)row;
        lcd_cur_col = (int8_t)col;
        lcd_changed = 1;
    }
}

static void lcd_glyph(int32_t x, int32_t y, uint8_t ch, int cursor)
{
    const uint8_t *g;
    int32_t cx, cy;
    uint32_t i = (uint8_t)(ch - 0x20u);
    g = FONT5X7[i < LCD_GLYPHS ? i : 0];
    for (cx = 0; cx < 5; cx++)
        for (cy = 0; cy < 8; cy++) {
            int on = cy < 7 ? (g[cx] >> cy) & 1 : cursor;
            cv_rect(x + cx * LCD_PITCH, y + cy * LCD_PITCH, LCD_DOT, LCD_DOT, on ? LCD_ON : LCD_OFF);
        }
}

/* the panel onto the screen, if anything changed */
static void lcd_draw(int force)
{
    uint32_t r, c;
    if (!lcd_changed && !force)
        return;
    lcd_changed = 0;
    cv_begin(240, LCD_H, LCD_GLASS);
    cv_rect(0, 0, 240, 1, LCD_EDGE);
    cv_rect(0, LCD_H - 1, 240, 1, LCD_EDGE);
    for (r = 0; r < LCD_ROWS; r++)
        for (c = 0; c < LCD_COLS; c++)
            lcd_glyph((int32_t)c * LCD_CW, LCD_PAD + (int32_t)r * (LCD_RH + LCD_GAP), (uint8_t)lcd_txt[r][c],
                      lcd_cur_row == (int32_t)r && lcd_cur_col == (int32_t)c && (plat_ms() / 400u) % 2u == 0u);
    cv_blit(0, LCD_Y);
}

/* ---- number formatting for the panel ---- */
static void str_cat(char *d, const char *s)
{
    while (*d)
        d++;
    while (*s)
        *d++ = *s++;
    *d = 0;
}

static void fmt_uint(char *b, uint32_t v, uint32_t width, char pad)
{
    char t[12];
    uint32_t n = 0, i;
    do
        t[n++] = (char)('0' + v % 10u);
    while ((v /= 10u) && n < 11u);
    for (i = n; i < width; i++)
        *b++ = pad;
    while (n)
        *b++ = t[--n];
    *b = 0;
}

static void fmt_signed(char *b, int32_t v, uint32_t width)   /* signed, sign always shown */
{
    *b++ = v < 0 ? '-' : '+';
    fmt_uint(b, (uint32_t)(v < 0 ? -v : v), width ? width - 1u : 0u, '0');
}

static void note_text(char *b, uint32_t note)   /* C3 = 60, as Akai and Alesis show it; C#3 three characters */
{
    static const char *const N[] = {"C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"};
    int32_t o = (int32_t)(note / 12u) - 2;
    b[0] = 0;
    str_cat(b, N[note % 12u]);
    if (o < 0) {
        char t[3] = {'-', (char)('0' - o), 0};
        str_cat(b, t);
    } else {
        char t[2] = {(char)('0' + o), 0};
        str_cat(b, t);
    }
}

