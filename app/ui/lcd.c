#define LCD_GLYPHS (sizeof(FONT5X7) / sizeof(FONT5X7[0]))
#define CH_BLOCK "\x7F"
#define CH_RIGHT "\x80"
#define CH_LEFT "\x81"
#define CH_UP "\x82"
#define CH_DOWN "\x83"
#define CH_PLAY "\x84"
